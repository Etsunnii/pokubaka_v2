const flattenDigisellerCategories = data => {
	const roots = asArray(data.category || data.categories || data.content || data.rows)
	const flat = []
	const usedNames = new Map()

	const visit = (category, parents = []) => {
		const id = getCategoryId(category)
		const ownName = getCategoryName(category)
		if (!id || !ownName) return

		const pathNames = [...parents, ownName]
		const baseName = normalizeCategoryName(pathNames.join(' '))
		const nameOwner = usedNames.get(baseName)
		const localName = nameOwner && String(nameOwner) !== String(id)
			? normalizeCategoryName(`${baseName} ${id}`)
			: baseName
		usedNames.set(baseName, id)

		flat.push({
			id: String(id),
			name: ownName,
			pathName: normalizeCategoryName(pathNames.join(' / ')),
			localName,
		})

		getCategoryChildren(category).forEach(child => visit(child, pathNames))
	}

	roots.forEach(category => visit(category))
	return flat
}

