const parseAccountEntry = entry => {
	if (typeof entry !== 'string') return { content: '', createdAt: null }
	try {
		const parsed = JSON.parse(entry)
		if (parsed && typeof parsed === 'object' && typeof parsed.content === 'string') {
			return { content: parsed.content, createdAt: parsed.createdAt || null }
		}
	} catch (_) {}
	return { content: entry, createdAt: null }
}

