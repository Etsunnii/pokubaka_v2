const recalcCategoryMinPrice = async categoryId => {
	if (!categoryId) return
	const categoryItems = await prisma.item.findMany({ where: { categoryId, isVisible: true } })
	const minPrice = categoryItems.reduce((min, item) => {
		if (!item.price) return min
		return min === 0 || item.price < min ? item.price : min
	}, 0)
	await prisma.category.update({ where: { id: categoryId }, data: { minPrice } })
}

