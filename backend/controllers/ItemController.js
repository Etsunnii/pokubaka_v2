export const getOneByName = async (req, res) => {
	try {
		const categorySlug = decodeURIComponent(req.params.categoryName || '')
		const itemSlug = decodeURIComponent(req.params.itemName || '')
		const categoryName = categorySlug.replace(/-/g, ' ')
		const itemName = itemSlug.replace(/-/g, ' ')

		const categories = await prisma.category.findMany({
			include: {
				items: { where: { isVisible: true } },
			},
		})
		const category = categories.find(item =>
			item.name === categoryName ||
			item.name === categorySlug ||
			createSlug(item.name) === categorySlug
		)
		const item = category?.items.find(product =>
			product.name === itemName ||
			product.name === itemSlug ||
			createSlug(product.name) === itemSlug
		)

		if (!category || !item) {
			return res.status(404).json({ message: 'Item not found' })
		}

		const sanitizedItem = removeSensitiveFields(item)
		res.json({
			...sanitizedItem,
			category: {
				id: category.id,
				name: category.name,
				type: category.type,
			},
		})
	} catch (err) {
		console.error('Item slug lookup error:', err)
		res.status(500).json({ message: 'Item lookup error' })
	}
}

